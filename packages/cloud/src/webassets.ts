// Files the Vercel site (apps/web) shares with the device: the browser sealing
// code and the secure-link wording. Generated so the two never drift:
//   node packages/cloud/src/webassets.ts      (rewrites apps/web/public/form-copy.js)
// A test fails if the committed file is stale.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { WEB_SEAL_SOURCE } from "@momo/protocol";
import { formCopy } from "./hosted/page.ts";

/** Stands in for the site name in the login wording; the page fills it in. */
export const SITE = "{site}";

export function webFormJs(): string {
  const copy = {
    login: formCopy({ kind: "login", label: SITE }),
    card: formCopy({ kind: "card", label: "" }),
    address: formCopy({ kind: "address", label: "" }),
  };
  return `// Generated by packages/cloud/src/webassets.ts. Do not edit.
${WEB_SEAL_SOURCE.trim()}
const MOMO_COPY = ${JSON.stringify(copy, null, 1)};
`;
}

export const WEB_FORM_JS_PATH = fileURLToPath(new URL("../../../apps/web/public/form-copy.js", import.meta.url));

if (import.meta.main) {
  writeFileSync(WEB_FORM_JS_PATH, webFormJs());
  console.log(`wrote ${WEB_FORM_JS_PATH}`);
}
